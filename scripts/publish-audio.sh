#!/usr/bin/env bash
# Publish audio/ MP3s to the GitHub Release "audio-v1" (flat asset names, free CDN-backed downloads).
#   bash scripts/publish-audio.sh            # upload everything
# Asset naming: audio/gita/2.47.mp3 -> gita_2.47.mp3 ; audio/katha/x--y.mp3 -> katha_x--y.mp3
set -euo pipefail
cd "$(dirname "$0")/.."
TAG=audio-v1
STAGE=$(mktemp -d)
for f in audio/*/*.mp3; do
  kind=$(basename "$(dirname "$f")")
  cp "$f" "$STAGE/${kind}_$(basename "$f")"
done
count=$(ls "$STAGE" | wc -l)
echo "staging $count files"
gh release view "$TAG" >/dev/null 2>&1 || gh release create "$TAG" --title "Narration audio v1" --notes "Neural Hindi narration (hi-IN-MadhurNeural) for shlokas, chapter summaries and stories. Generated by scripts/make-audio.py." --latest=false
# upload in batches of 40 to keep each gh call short; --clobber replaces changed files
ls "$STAGE" | xargs -n 40 | while read -r batch; do
  files=()
  for b in $batch; do files+=("$STAGE/$b"); done
  gh release upload "$TAG" "${files[@]}" --clobber
  echo "uploaded batch"
done
rm -rf "$STAGE"
gh release view "$TAG" --json assets --jq '.assets | length'
